using IncidentPlatform.Api.Models;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace IncidentPlatform.Api.Data;

public class IncidentNumberSequenceConfiguration : IEntityTypeConfiguration<IncidentNumberSequence>
{
    public void Configure(EntityTypeBuilder<IncidentNumberSequence> builder)
    {
        builder.ToTable("IncidentNumberSequences");

        // Year itself is the PK (database-design.md §4.13) — no separate
        // surrogate Id needed, since "one row per year" is exactly what a
        // natural key is for here, and there are no FKs pointing at this
        // table that would suffer if the key ever needed to change.
        builder.HasKey(s => s.Year);

        // Explicitly NOT auto-increment — Year is supplied by the service
        // (DateTime.UtcNow.Year), not generated by the database.
        builder.Property(s => s.Year).ValueGeneratedNever();

        builder.Property(s => s.UpdatedAt).HasColumnType("datetime(6)");
    }
}
